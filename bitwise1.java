 class BitwiseEx1
 {
 public static void main(String[] args)
    {
        int a = 5;
        int b = 3;

        int andResult = a & b;
        int orResult = a | b;
        int xorResult = a ^ b;

        System.out.println(andResult);
        System.out.println(orResult);
        System.out.println(xorResult);
    }
}
